"""Register the approved face pixels against measured eyes and mouth in each pose.

Input is local output from register-face-landmarks.swift. Never infer placements
from a whole-head rectangle: pose perspective and hair change those bounds.
"""
from pathlib import Path
import hashlib
import json
import math
import statistics
import sys
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / 'assets/trip-world'
rows = [json.loads(line) for line in Path(sys.argv[1]).read_text().splitlines() if line.startswith('{')]
measured = {}
for row in rows:
    assert len(row['faces']) == 1, row['id']
    face = row['faces'][0]
    assert face['confidence'] > .9, row['id']
    measured[row['id']] = face['eyes'] + [face['mouth']]

def matrix(source, target):
    (x1,y1),(x2,y2),(x3,y3) = source
    determinant = (x2-x1)*(y3-y1)-(x3-x1)*(y2-y1)
    assert abs(determinant) > 1
    def solve(values):
        p1,p2,p3 = values
        a=((p2-p1)*(y3-y1)-(p3-p1)*(y2-y1))/determinant
        b=((x2-x1)*(p3-p1)-(x3-x1)*(p2-p1))/determinant
        return a,b,p1-a*x1-b*y1
    a,c,e=solve([p[0] for p in target]);b,d,f=solve([p[1] for p in target])
    assert a*d-b*c > 0, 'Reflected face'
    return [round(x,8) for x in (a,b,c,d,e,f)]

def skin(file, points):
    image=Image.open(file).convert('RGBA')
    (x1,y1),(x2,y2),(xm,ym)=points
    distance=math.hypot(x2-x1,y2-y1)
    cx=(x1+x2+xm)/3;cy=(y1+y2+ym)/3+distance*.16
    rx=distance*.47;ry=distance*.40
    samples=[]
    for y in range(max(0,int(cy-ry)),min(image.height,int(cy+ry)+1)):
        for x in range(max(0,int(cx-rx)),min(image.width,int(cx+rx)+1)):
            if ((x-cx)/rx)**2+((y-cy)/ry)**2 > 1:continue
            r,g,b,a=image.getpixel((x,y))
            if a>220 and r>110 and r-g>12 and g-b>5:samples.append((r,g,b))
    assert len(samples)>10,file
    return [statistics.median(p[c] for p in samples) for c in range(3)]

source={kind:measured['master-'+kind] for kind in 'kh'}
base_skin={kind:skin(ART/'characters-base.png',source[kind]) for kind in 'kh'}
poses={}
for name,points in measured.items():
    if name.startswith('master-'):continue
    kind='h' if name.startswith('helena-') or name.endswith('-h') else 'k'
    file=name.rsplit('-',1)[0]+'.webp'
    target_skin=skin(ART/file,points)
    gains=[round(max(.82,min(1.18,t/s)),4) for t,s in zip(target_skin,base_skin[kind])]
    poses[name]={'kind':kind,'points':[[round(v,5) for v in p] for p in points],
                 'matrix':matrix(source[kind],points),'gains':gains}
data={'masterSha256':hashlib.sha256((ART/'characters-base.png').read_bytes()).hexdigest(),
      'source':{k:[[round(v,5) for v in p] for p in value] for k,value in source.items()},'poses':poses}
output='''/* Measured registration of immutable approved face pixels. Generated by scripts/build-face-registration.py. */
(function(root,factory){if(typeof module==='object'&&module.exports)module.exports=factory();else root.TripFaceRegistration=factory();})(typeof globalThis!=='undefined'?globalThis:this,function(){return '''+json.dumps(data,separators=(',',':'))+''';});\n'''
(ROOT/'assets/face-registration.js').write_text(output)
print(f'Registered {len(poses)} faces from eyes and mouth, with scene lighting.')
